from pathlib import Path

from buildrail.providers import ProviderGateway
from buildrail.providers.adapters.fake import FakeProvider
from buildrail.providers.errors import AuthenticationError
from buildrail.skill_protocol import RunContext, SkillRequest
from buildrail.skills import SkillRegistry

_SKILL_SOURCE = (
    Path(__file__).resolve().parents[3] / "skills" / "generate-docs" / "skill.py"
).read_text(encoding="utf-8")


def _request(inputs: dict[str, str]) -> SkillRequest:
    return SkillRequest(
        protocol_version="1.0",
        run_context=RunContext(run_id="20260804-000000-test", step_index=1, workdir="."),
        inputs=inputs,
        config={},
    )


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def test_skill_source_never_imports_a_concrete_provider_adapter_or_core_internals() -> None:
    assert "import buildrail.providers.adapters" not in _SKILL_SOURCE
    assert "from buildrail.providers.adapters" not in _SKILL_SOURCE
    assert "import buildrail.core" not in _SKILL_SOURCE
    assert "from buildrail.core" not in _SKILL_SOURCE


def _sample_repo(tmp_path: Path) -> Path:
    _write(
        tmp_path / "pyproject.toml",
        '[project]\nname = "x"\nrequires-python = ">=3.12"\n'
        '[project.scripts]\nmytool = "app.main:run"\n'
        "[tool.ruff]\n[tool.mypy]\n[tool.pytest.ini_options]\n",
    )
    _write(tmp_path / "app" / "__init__.py", "")
    _write(tmp_path / "app" / "main.py", '"""Entry point."""\n\n\ndef run():\n    pass\n')
    _write(tmp_path / "tests" / "test_main.py", "def test_ok():\n    assert True\n")
    return tmp_path


def test_run_generates_all_three_documents_without_a_provider(tmp_path: Path) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")

    response = run_docs(_request({"repository_path": str(repo)}), None)

    assert response.status == "success"
    assert set(response.outputs) == {"project_overview", "module_reference", "development_guide"}
    for output in response.outputs.values():
        assert output.artifact_type == "documentation"
        assert "Generated by Buildrail" in output.content
        assert output.metadata == {"enhanced": False}
        assert output.usage is None


def test_project_overview_contains_expected_facts(tmp_path: Path) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")

    response = run_docs(_request({"repository_path": str(repo)}), None)

    content = response.outputs["project_overview"].content
    assert "mytool" in content
