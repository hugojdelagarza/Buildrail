def test_run_does_not_construct_a_provider_without_enhance(tmp_path: Path) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")

    # Passing provider=None and inputs without "enhance" must succeed — if the skill
    # tried to call a provider here, this would raise AttributeError on None.
    response = run_docs(_request({"repository_path": str(repo)}), None)

    assert response.status == "success"


def test_run_fails_cleanly_when_enhance_is_set_but_no_provider_is_supplied(
    tmp_path: Path,
) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")

    response = run_docs(_request({"repository_path": str(repo), "enhance": "true"}), None)

    assert response.status == "failure"
    assert response.error is not None


def test_enhance_path_uses_only_the_provider_gateway_and_marks_metadata(tmp_path: Path) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")
    gateway = ProviderGateway(FakeProvider())

    response = run_docs(_request({"repository_path": str(repo), "enhance": "true"}), gateway)

    assert response.status == "success"
    for output in response.outputs.values():
        assert output.metadata == {"enhanced": True}
        assert output.usage is not None
        assert output.model_used == "fake-model"


def test_enhancement_cannot_replace_deterministic_facts_with_invented_facts(
    tmp_path: Path,
) -> None:
    repo = _sample_repo(tmp_path)
    _write(repo / "app" / "helper.py", "from app.main import run\n")
    run_docs = SkillRegistry().resolve("generate-docs")

    enhanced = run_docs(
        _request({"repository_path": str(repo), "enhance": "true"}),
        ProviderGateway(FakeProvider()),
    )

    # The model is only ever asked for a short intro paragraph; every fact
    # (entry points, modules, quality commands) is always rendered by our
    # own deterministic code and must survive verbatim in the enhanced doc.
    assert "app.main:run" in enhanced.outputs["project_overview"].content
    assert "app.helper" in enhanced.outputs["module_reference"].content
    assert "app.main" in enhanced.outputs["module_reference"].content
    assert "pytest -v" in enhanced.outputs["development_guide"].content
    assert "mypy" in enhanced.outputs["development_guide"].content


def test_enhance_surfaces_provider_errors_as_a_failed_response(tmp_path: Path) -> None:
    repo = _sample_repo(tmp_path)
    run_docs = SkillRegistry().resolve("generate-docs")
    gateway = ProviderGateway(FakeProvider(error=AuthenticationError("no key")))

    response = run_docs(_request({"repository_path": str(repo), "enhance": "true"}), gateway)

    assert response.status == "failure"
    assert "no key" in (response.error or "")


def test_run_fails_cleanly_without_a_repository_path() -> None:
    run_docs = SkillRegistry().resolve("generate-docs")

    response = run_docs(_request({}), None)

    assert response.status == "failure"
